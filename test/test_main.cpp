// Shared gtest entry point for tests that link sisl (-> boost). Providing main() as a direct object beats
// boost's test_exec_monitor archive (whose own main() references an undefined test_main), which the linker
// would otherwise pull ahead of libgtest_main.a. HomeStore-free tests (test_wire) can use GTest::gtest_main.

#include <gtest/gtest.h>

int main(int argc, char** argv) {
    ::testing::InitGoogleTest(&argc, argv);
    return RUN_ALL_TESTS();
}
